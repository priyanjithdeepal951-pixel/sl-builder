export function createCanvasBlockFromTemplate(tpl: WebStudioBlockTemplate): CanvasBlock {
  const cloneChildren = (children?: CanvasBlock[]): CanvasBlock[] | undefined =>
    children?.map((c, idx) => ({
      ...c,
      id: `blk_${Date.now()}_${idx}_${Math.random().toString(36).slice(2, 6)}`,
      style: { ...(c.style || {}) },
      options: c.options ? [...c.options] : undefined,
      children: cloneChildren(c.children),
    }));

  return {
    id: `blk_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    type: tpl.type,
    category: tpl.blockCategory,
    name: tpl.name,
    content: tpl.defaultContent,
    subtitle: tpl.defaultSubtitle,
    ...tpl.defaults,
    style: { ...(tpl.defaults.style || {}) },
    logicConfig: tpl.defaults.logicConfig ? { ...tpl.defaults.logicConfig } : undefined,
    options: tpl.defaults.options ? [...tpl.defaults.options] : undefined,
    children: cloneChildren(tpl.defaults.children),
  };
}

export function getCategoryMetaForBlockType(type: BlockType): WebStudioCategoryMeta {
  const match = WEB_STUDIO_BLOCK_TEMPLATES.find((t) => t.type === type);
  const catId = match?.studioCategory || 'layout';
  return (
    WEB_STUDIO_CATEGORIES.find((c) => c.id === catId) || WEB_STUDIO_CATEGORIES[0]
  );
}
